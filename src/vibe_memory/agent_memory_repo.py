"""Agent Memory Repo interoperability and agent-led maintenance helpers.

The service never parses a foreign repository or infers keywords. Export is a
deterministic projection of stored records. Import accepts entries and keywords
that a connected agent already extracted, then requires a snapshot-bound diff
approval before creating quarantined imported records.
"""

from __future__ import annotations

import hashlib
import io
import json
import re
import zipfile
from collections import Counter, defaultdict
from datetime import datetime
from uuid import NAMESPACE_URL, uuid5

from .clock import utc_now_iso
from .corrections import annotate_corrections
from .security import prepare_record_security, record_fingerprint
from .store import NotFound

ADAPTER_VERSION = "1.0"
EXPORT_FORMAT = "agent-memory-repo"
MAX_EXPORT_RECORDS = 10000


class SnapshotConflict(Exception):
    """The imported entry set or current memory changed after dry-run approval."""


def _canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _digest(value):
    return hashlib.sha256(_canonical(value).encode("utf-8")).hexdigest()


def _updated_at(record):
    history = record.get("writer_history") or []
    return max(
        (item.get("at", "") for item in history if item.get("at")),
        default=record["created_at"],
    )


def _all_records(store, owner, include_untrusted=False, include_quarantined=False):
    records, offset = [], 0
    while len(records) < MAX_EXPORT_RECORDS:
        page = store.list(
            owner,
            limit=min(500, MAX_EXPORT_RECORDS - len(records)),
            offset=offset,
            include_untrusted=include_untrusted,
            include_quarantined=include_quarantined,
        )
        records.extend(page)
        if len(page) < 500:
            break
        offset += len(page)
    return records


def _safe_inline(value):
    return re.sub(r"\s+", " ", str(value or "")).strip().replace("[", "\\[").replace("]", "\\]")


def _record_markdown(record):
    title = record.get("title") or record.get("content", "")[:100] or "Untitled memory"
    metadata = {
        "vibe_memory_id": record["id"],
        "kind": record["kind"],
        "subtype": record.get("subtype", ""),
        "version": record["version"],
        "content_hash": record.get("content_hash", ""),
        "created_at": record["created_at"],
        "updated_at": _updated_at(record),
        "source": record.get("source", ""),
        "keywords": record.get("keywords") or [],
        "tags": record.get("tags") or [],
        "trust_level": record.get("trust_level", "trusted"),
        "security_state": record.get("security_state", "active"),
    }
    return (
        f"# {title}\n\n"
        + (record.get("content") or "")
        + "\n\n## Vibe Memory metadata\n\n```json\n"
        + json.dumps(metadata, ensure_ascii=False, indent=2)
        + "\n```\n"
    ).encode("utf-8")


def export_agent_memory_repo(
    store,
    owner,
    namespace_id,
    *,
    include_untrusted=False,
    include_quarantined=False,
):
    if include_quarantined and not include_untrusted:
        raise ValueError("include_quarantined requires include_untrusted")
    records = _all_records(store, owner, include_untrusted, include_quarantined)
    records.sort(key=lambda item: (item["kind"], item["created_at"], item["id"]))
    grouped = defaultdict(list)
    files = {}
    for record in records:
        grouped[record["kind"]].append(record)
        files[f"records/{record['id']}.md"] = _record_markdown(record)

    memory_lines = [
        "# Memory",
        "",
        "Portable Agent Memory Repo projection generated by Vibe Memory.",
        "Vibe Memory remains the source of truth; Vault values and credentials are never exported.",
        "",
    ]
    for kind in sorted(grouped):
        topic_path = f"topics/{kind}.md"
        memory_lines.append(f"- [[{topic_path.removesuffix('.md')}]] — {kind.title()} records")
        topic_lines = [f"# {kind.title()}", ""]
        for record in grouped[kind]:
            title = _safe_inline(record.get("title") or record.get("content", "")[:100])
            source = _safe_inline(record.get("source")) or "Vibe Memory"
            added = record["created_at"][:10]
            topic_lines.append(
                f"- [[records/{record['id']}]] — {title} [source: {source}; added: {added}]"
            )
        topic_lines.append("")
        files[topic_path] = "\n".join(topic_lines).encode("utf-8")
    files["MEMORY.md"] = "\n".join(memory_lines).encode("utf-8") + b"\n"

    exported_at = utc_now_iso()
    manifest = {
        "format": EXPORT_FORMAT,
        "adapter_version": ADAPTER_VERSION,
        "exported_at": exported_at,
        "time_basis": "UTC",
        "namespace": namespace_id,
        "source_of_truth": "vibe-memory",
        "record_count": len(records),
        "credentials_included": False,
        "vault_included": False,
        "raw_files_included": False,
        "security_selection": {
            "include_untrusted": include_untrusted,
            "include_quarantined": include_quarantined,
        },
        "files": {
            name: {"bytes": len(value), "sha256": hashlib.sha256(value).hexdigest()}
            for name, value in sorted(files.items())
        },
    }
    files["vibe-memory-export.json"] = json.dumps(
        manifest, ensure_ascii=False, indent=2
    ).encode("utf-8")
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, value in sorted(files.items()):
            archive.writestr(name, value)
    return output.getvalue(), manifest


def _entry_title(entry):
    return entry.title or re.sub(r"\s+", " ", entry.content).strip()[:100]


def _entry_claim(entry):
    return {
        "client_request_id": entry.client_request_id,
        "title": _entry_title(entry),
        "content_hash": record_fingerprint(_entry_title(entry), entry.content),
        "kind": entry.kind,
        "keywords": entry.keywords,
        "source": entry.source,
        "tags": entry.tags,
        "path": entry.path,
        "line": entry.line,
        "added_at": entry.added_at.isoformat() if entry.added_at else None,
        "links": entry.links,
    }


def agent_memory_repo_diff(store, owner, data):
    records = _all_records(store, owner, True, True)
    by_hash = defaultdict(list)
    by_coordinate = defaultdict(list)
    for record in records:
        by_hash[record.get("content_hash", "")].append(record)
        source = (record.get("metadata") or {}).get("agent_memory_repo") or {}
        coordinate = (source.get("repository"), source.get("path"), source.get("line"))
        if all(value is not None for value in coordinate):
            by_coordinate[coordinate].append(record)

    items = []
    for entry in data.entries:
        claim = _entry_claim(entry)
        content_hash = claim["content_hash"]
        coordinate = (data.repository, entry.path, entry.line)
        if by_hash[content_hash]:
            classification = "unchanged"
            matches = sorted(record["id"] for record in by_hash[content_hash])
        elif by_coordinate[coordinate]:
            classification = "conflicting_entry"
            matches = sorted(record["id"] for record in by_coordinate[coordinate])
        else:
            classification = "create"
            matches = []
        items.append(
            {
                "client_request_id": entry.client_request_id,
                "path": entry.path,
                "line": entry.line,
                "classification": classification,
                "matching_record_ids": matches,
                "content_hash": content_hash,
            }
        )

    input_claim = {
        "repository": data.repository,
        "revision": data.revision,
        "entries": [_entry_claim(entry) for entry in data.entries],
    }
    snapshot = sorted(
        (record["id"], record["version"], record.get("content_hash", "")) for record in records
    )
    diff_hash = _digest({"input": input_claim, "snapshot": snapshot})
    return {
        "adapter": EXPORT_FORMAT,
        "adapter_version": ADAPTER_VERSION,
        "dry_run": True,
        "llm_calls": 0,
        "server_parsed_repository": False,
        "repository": data.repository,
        "revision": data.revision,
        "items": items,
        "stats": dict(sorted(Counter(item["classification"] for item in items).items())),
        "diff_hash": diff_hash,
    }


def apply_agent_memory_repo(
    store,
    embedder,
    owner,
    data,
    agent_id,
    agent_name,
):
    from .models import AgentMemoryRepoDiffInput

    diff_input = AgentMemoryRepoDiffInput.model_validate(
        data.model_dump(
            exclude={"approved_diff_hash", "approved_client_request_ids", "reason"}
        )
    )
    current = agent_memory_repo_diff(store, owner, diff_input)
    if current["diff_hash"] != data.approved_diff_hash.lower():
        raise SnapshotConflict()
    classifications = {
        item["client_request_id"]: item["classification"] for item in current["items"]
    }
    invalid = [
        client_id
        for client_id in data.approved_client_request_ids
        if classifications.get(client_id) != "create"
    ]
    if invalid:
        raise ValueError("approved IDs must refer only to create items")

    approved = set(data.approved_client_request_ids)
    created = []
    for entry in data.entries:
        if entry.client_request_id not in approved:
            continue
        title = _entry_title(entry)
        origin_url = data.repository if data.repository.startswith(("http://", "https://")) else ""
        provenance = {
            "source_type": "imported",
            "origin_agent": agent_name or "Agent Memory Repo adapter",
            "origin_url": origin_url,
            "collected_at": utc_now_iso(),
            "content_type": "text/markdown; profile=agent-memory-repo",
            "scan_verdict": "not_scanned",
            "scan_evidence": [],
        }
        security = prepare_record_security(title, entry.content, provenance)
        record_id = str(
            uuid5(
                NAMESPACE_URL,
                "\0".join(
                    (
                        owner,
                        data.repository,
                        data.revision,
                        entry.path,
                        str(entry.line),
                        security["content_hash"],
                    )
                ),
            )
        )
        try:
            existing = store.get(owner, record_id, internal=True)
            created.append(
                {"client_request_id": entry.client_request_id, "status": "unchanged", "record": existing}
            )
            continue
        except NotFound:
            pass
        metadata = {
            "agent_memory_repo": {
                "format": EXPORT_FORMAT,
                "adapter_version": ADAPTER_VERSION,
                "repository": data.repository,
                "revision": data.revision,
                "path": entry.path,
                "line": entry.line,
                "added_at": entry.added_at.isoformat() if entry.added_at else None,
                "links": entry.links,
                "approval_reason": data.reason,
            }
        }
        record = store.insert(
            owner,
            "memory",
            entry.content,
            title,
            entry.source or f"Agent Memory Repo: {entry.path}:{entry.line}",
            entry.tags,
            entry.kind,
            entry.keywords,
            metadata,
            embedder.keywords(entry.keywords),
            record_id=record_id,
            security=security,
            creator_agent_id=agent_id,
            creator_agent_name=agent_name,
        )
        created.append(
            {"client_request_id": entry.client_request_id, "status": "created", "record": record}
        )
    return {
        "adapter": EXPORT_FORMAT,
        "adapter_version": ADAPTER_VERSION,
        "dry_run": False,
        "approved_diff_hash": current["diff_hash"],
        "created": created,
        "quarantine_required": True,
    }


def memory_maintenance_audit(store, owner, data):
    records = _all_records(
        store, owner, data.include_untrusted, data.include_quarantined
    )
    annotate_corrections(store, owner, records)
    relations, cursor = [], 0
    while True:
        page = store.relations(owner, status="active", limit=500, cursor=cursor)
        relations.extend(page)
        if len(page) < 500:
            break
        cursor += len(page)
    degree = Counter()
    for relation in relations:
        degree[relation["source_id"]] += 1
        degree[relation["target_id"]] += 1
    duplicate_hashes = defaultdict(list)
    for record in records:
        duplicate_hashes[record.get("content_hash", "")].append(record)

    def projection(record):
        return {
            "id": record["id"],
            "kind": record["kind"],
            "subtype": record.get("subtype", ""),
            "version": record["version"],
            "updated_at": _updated_at(record),
            "keyword_count": len(record.get("keywords") or []),
            "relation_degree": degree[record["id"]],
            "trust_level": record.get("trust_level"),
            "security_state": record.get("security_state"),
        }

    duplicate_groups = [
        {
            "content_hash": fingerprint,
            "records": [projection(record) for record in sorted(items, key=lambda item: item["id"])],
        }
        for fingerprint, items in sorted(duplicate_hashes.items())
        if fingerprint and len(items) > 1
    ][: data.candidate_limit]
    stale = []
    if data.stale_before:
        stale = [
            projection(record)
            for record in records
            if datetime.fromisoformat(_updated_at(record)) < data.stale_before
        ][: data.candidate_limit]
    weak_index = [
        projection(record)
        for record in records
        if len(record.get("keywords") or []) < data.minimum_keywords
    ][: data.candidate_limit]
    unsourced = [
        projection(record)
        for record in records
        if not record.get("source")
        and not (record.get("provenance") or {}).get("origin_url")
        and not (record.get("provenance") or {}).get("origin_agent")
    ][: data.candidate_limit]
    orphans = [
        projection(record) for record in records if not degree[record["id"]]
    ][: data.candidate_limit]
    unresolved = [
        projection(record)
        for record in records
        if record.get("correction_status") == "unresolved"
    ][: data.candidate_limit]
    snapshot = _digest(
        {
            "records": sorted(
                (record["id"], record["version"], record.get("content_hash", ""))
                for record in records
            ),
            "relations": sorted(
                (edge["id"], edge["version"], edge["status"]) for edge in relations
            ),
        }
    )
    return {
        "generated_at": utc_now_iso(),
        "time_basis": "UTC",
        "snapshot": snapshot,
        "llm_calls": 0,
        "content_included": False,
        "server_recommendations": False,
        "stats": {
            "records": len(records),
            "relations": len(relations),
            "exact_duplicate_groups": len(duplicate_groups),
            "stale_candidates": len(stale),
            "weak_index_candidates": len(weak_index),
            "unsourced_candidates": len(unsourced),
            "orphan_candidates": len(orphans),
            "unresolved_corrections": len(unresolved),
        },
        "exact_duplicate_groups": duplicate_groups,
        "stale_candidates": stale,
        "weak_index_candidates": weak_index,
        "unsourced_candidates": unsourced,
        "orphan_candidates": orphans,
        "unresolved_corrections": unresolved,
        "next_action": (
            "A connected agent must fetch selected records, evaluate evidence, present exact "
            "record and graph changes for user approval, then use version-checked existing APIs."
        ),
    }
